countries=("Japan") # "South_Korea" "China" "United_States")
sample_nums=(200 500 1000 2000) # 3000)

for country in "${countries[@]}"; do
    for sample_num in "${sample_nums[@]}"; do
        echo "select $sample_num data generated by qwen for $country"
        python 2.data_selection.py \
            --country "$country" \
            --select_score "rep_dist" \
            --sample_num $sample_num \
            --prefix "rep_dist" \
            --round 1 \
            --cluster_threshold 0.15 \
            --main_generator "qwen/qwen3-8b" \
            --output_dir ./data  # >> ./logs/3.data_selection.log
    done
done